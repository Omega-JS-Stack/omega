/**
 * stage-functions — the backend consumer build step (src/dist pillar).
 *
 * `functions/` is GENERATED OUTPUT, staged fresh from the authored app tree:
 *
 *   src/**                → functions/**            (1:1 copy, no transforms)
 *   package.json          → functions/package.json  (derived: name/engines/deps)
 *   config layers         → functions/config/omega.json5 (composeTargetConfig —
 *                           brand⊕app flattened; the deployed runtime cannot
 *                           walk up past the upload boundary, cp100e)
 *   .env                  → functions/.env          (verbatim copy — disperse
 *                           composes brand-level values into the APP .env now)
 *   .nvmrc                → functions/.nvmrc
 *   service-account.json  → functions/service-account.json
 *
 * The stage is a full re-stage on every call (consumer src is small), with a
 * preserve list for runtime artifacts that live inside functions/ between
 * stages: node_modules/ (self-test symlinks, legacy installs) and *.log
 * (dev/emulator/test/deploy logs — co-located with firebase-tools' logs by
 * design, see docs/logging.md). Everything else is wiped first, so a file
 * deleted from src/ disappears from the stage and a stale composed config can
 * never shadow a brand edit.
 *
 * node_modules is NOT staged: local runs resolve up from functions/ to the
 * app root's install (plain Node resolution); deploys keep cp100d's
 * stage-local-packages (packed file: deps + lockfile) on top of this stage.
 */
const path = require('path');
const jetpack = require('fs-jetpack');
const { composeTargetConfig } = require('@omega.js/config');

// functions/ entries that survive a re-stage (runtime artifacts, never authored)
const PRESERVE = [/^node_modules$/, /\.log$/];

const CONFIG_BANNER = '// Staged by `omega build` (brand+app config layers flattened for the runtime\n'
  + '// and the deploy upload boundary). GENERATED — edit the brand/app omega.json5.\n';

/**
 * Stage the authored app tree into functions/.
 * @param {object} options
 * @param {string} options.projectDir - The app root (firebaseProjectPath).
 * @param {function} [options.log] - Line logger (silent by default).
 * @returns {{ functionsDir: string, staged: string[] }} staged = relative paths written.
 */
function stageFunctions(options) {
  const projectDir = options.projectDir;
  const log = options.log || (() => {});
  const srcDir = path.join(projectDir, 'src');
  const functionsDir = path.join(projectDir, 'functions');
  const staged = [];

  const appPackage = jetpack.read(path.join(projectDir, 'package.json'), 'json');
  if (!appPackage) {
    throw new Error(`No package.json at ${projectDir} — a backend app's manifest lives at the APP ROOT (src/dist pillar); run npx omega setup first`);
  }
  if (!jetpack.exists(srcDir)) {
    throw new Error(`No src/ under ${projectDir} — backend apps are src-first: authored code lives in src/ and functions/ is staged output (run npx omega setup to scaffold, or move your functions code into src/)`);
  }

  // ─── Wipe previous stage (preserve runtime artifacts) ─────────────────────
  for (const entry of jetpack.list(functionsDir) || []) {
    if (PRESERVE.some((pattern) => pattern.test(entry))) continue;
    jetpack.remove(path.join(functionsDir, entry));
  }

  // ─── src/** → functions/** ────────────────────────────────────────────────
  jetpack.copy(srcDir, functionsDir, { overwrite: true });
  staged.push('src/** → functions/**');

  // ─── Derived manifest (name/engines/runtime deps only) ────────────────────
  // Relative file: deps are spelled from the APP ROOT in the authored
  // manifest; the staged copy lives one level deeper, so they respell with a
  // leading ../ (stage-local-packages resolves them from functions/ at deploy).
  const dependencies = {};
  for (const [dep, spec] of Object.entries(appPackage.dependencies || {})) {
    dependencies[dep] = /^file:(?!\/)/.test(spec) ? `file:../${spec.slice('file:'.length)}` : spec;
  }

  const name = String(appPackage.name || path.basename(projectDir));
  const manifest = {
    name: name.endsWith('-functions') ? name : `${name}-functions`,
    version: appPackage.version || '0.0.1',
    description: `Staged Cloud Functions for ${name} — GENERATED by omega build, do not edit`,
    private: true,
    main: 'index.js',
    engines: appPackage.engines || { node: String(parseInt(process.versions.node, 10)) },
    dependencies,
  };
  jetpack.write(path.join(functionsDir, 'package.json'), JSON.stringify(manifest, null, 2) + '\n');
  staged.push('package.json (derived)');

  // ─── Composed config (the wipe above guarantees a stale stage never feeds
  //     back into the compose as an app layer) ───────────────────────────────
  const { config } = composeTargetConfig(projectDir, 'backend');
  jetpack.write(
    path.join(functionsDir, 'config', 'omega.json5'),
    CONFIG_BANNER + JSON.stringify(config, null, 2) + '\n',
  );
  staged.push('config/omega.json5 (composed)');

  // ─── App-root files that ride the artifact ────────────────────────────────
  for (const file of ['.env', '.nvmrc', 'service-account.json']) {
    const source = path.join(projectDir, file);
    if (!jetpack.exists(source)) continue;
    jetpack.copy(source, path.join(functionsDir, file), { overwrite: true });
    staged.push(file);
  }

  log(`Staged functions/ from src/ (${staged.length} steps)`);
  return { functionsDir, staged };
}

/**
 * Watch src/ (+ the app-root files that ride the artifact) and re-stage on
 * change. The Firebase emulator watches the functions dir natively, so a
 * re-stage IS the hot reload — no trigger file needed for consumer edits.
 * @param {object} options
 * @param {string} options.projectDir
 * @param {function} [options.log]
 * @param {number} [options.debounceMs]
 * @returns {{ close: function }}
 */
function watchAndStage(options) {
  const fs = require('fs');
  const projectDir = options.projectDir;
  const log = options.log || (() => {});
  const debounceMs = options.debounceMs || 250;
  const watchers = [];
  let timer = null;

  const restage = () => {
    clearTimeout(timer);
    timer = setTimeout(() => {
      try {
        stageFunctions({ projectDir });
        log('Re-staged functions/ (src changed)');
      } catch (error) {
        log(`Re-stage failed: ${error.message}`);
      }
    }, debounceMs);
  };

  const srcDir = path.join(projectDir, 'src');
  if (jetpack.exists(srcDir)) {
    watchers.push(fs.watch(srcDir, { recursive: true }, restage));
  }

  return {
    close: () => {
      clearTimeout(timer);
      for (const watcher of watchers) watcher.close();
    },
  };
}

module.exports = { stageFunctions, watchAndStage, PRESERVE };
