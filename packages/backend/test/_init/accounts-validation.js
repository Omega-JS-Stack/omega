const { TEST_ACCOUNTS } = require('../../dist/test/test-accounts.js');

/**
 * Test: Account Structure Validation
 * Verifies that all test accounts were created with the expected User helper fields
 * This catches failures in auth:on-create before other tests run
 */
module.exports = {
  description: 'Test accounts have required User structure',
  auth: 'none',
  timeout: 10000,

  async run({ accounts, expect, firestore }) {
    const accountIds = Object.keys(TEST_ACCOUNTS);

    for (const accountId of accountIds) {
      const account = accounts[accountId];

      // Check account was fetched
      expect(account, `Account '${accountId}' should exist in accounts object`).toBeTruthy();
      expect(account.uid, `Account '${accountId}' should have uid`).toBeTruthy();

      // Fetch full user doc from Firestore
      const userDoc = await firestore.get(`users/${account.uid}`);

      expect(userDoc, `User doc for '${accountId}' should exist in Firestore`).toBeTruthy();

      // Validate auth fields (set by on-create)
      expect(userDoc, `Account '${accountId}' should have auth.uid`).toHaveProperty('auth.uid');
      expect(userDoc, `Account '${accountId}' should have auth.email`).toHaveProperty('auth.email');

      // Validate API fields (generated by on-create via User helper)
      expect(userDoc, `Account '${accountId}' should have api.clientId`).toHaveProperty('api.clientId');
      expect(userDoc, `Account '${accountId}' should have api.privateKey`).toHaveProperty('api.privateKey');

      // Validate privateKey was fetched correctly
      expect(account.privateKey, `Account '${accountId}' privateKey should be fetched`).toBeTruthy();
      expect(account.privateKey, `Account '${accountId}' fetched privateKey should match Firestore`).toBe(userDoc.api.privateKey);

      // Validate affiliate code (generated by on-create via User helper)
      expect(userDoc, `Account '${accountId}' should have affiliate.code`).toHaveProperty('affiliate.code');

      // Validate metadata.created (set by on-create via User helper)
      expect(userDoc, `Account '${accountId}' should have metadata.created.timestamp`).toHaveProperty('metadata.created.timestamp');
      expect(userDoc, `Account '${accountId}' should have metadata.created.timestampUNIX`).toHaveProperty('metadata.created.timestampUNIX');

      // Validate subscription fields (merged from test account properties)
      expect(userDoc, `Account '${accountId}' should have subscription.product.id`).toHaveProperty('subscription.product.id');
      expect(userDoc, `Account '${accountId}' should have subscription.status`).toHaveProperty('subscription.status');
    }

    return { success: true };
  },
};
