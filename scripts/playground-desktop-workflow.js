/**
 * The playground's desktop release run, rendered into THIS repo's own
 * `.github/workflows/` ([#802](https://github.com/Omega-JS-Stack/omega/issues/802)).
 *
 * GitHub executes workflows from a repo ROOT only, and the playground brand is a
 * directory inside this monorepo, so the file its desktop target composes at
 * `brands/omega-playground/.github/workflows/desktop-build.yml` is a file GitHub
 * never sees. The release run (hosted build, the self-hosted EV-token Windows
 * signer registered to the Omega-JS-Stack org, finalize) therefore has no repo to
 * run in. Ian (2026-09-07): it runs from a snapshot of this tree in the brand's
 * own private rehearsal repo, which is where this rendered file goes and the only
 * place it lives (it is gitignored here, and
 * `scripts/playground-desktop-rehearsal.js` renders it before every run).
 *
 * This script renders exactly what the brand's file is rendered from, so a
 * template change reaches the run with one command:
 *
 *   1. the @omega.js/desktop workflow template, through the framework's own
 *      render context (`{{ versions.node }}` from the pinned Electron runtime,
 *      `{{ githubSecrets }}` from the env schema's delivery declarations)
 *   2. `@omega.js/devkit/ci-workflows`' `composeWorkflow`, target path
 *      `brands/omega-playground/targets/desktop`, so every post-checkout step
 *      runs in the target exactly as it does at a brand root
 *   3. the two monorepo-only edits below, applied AFTER composition because a
 *      brand needs neither: the local-era root install, and `npm ci` becoming
 *      `npm install` in the target
 *
 * Both installs are `npm install`: the target's because the lockfile npm would
 * read there is the brand root's, which is not committed, and the root's because
 * the rehearsal runs on a snapshot of a working tree whose lockfile may lag its
 * package.json files (`npm ci` refuses that; `npm install` heals it).
 *
 * Run: `node scripts/playground-desktop-workflow.js` (writes the file);
 * `scripts/playground-desktop-workflow.test.js` renders it and reads what the
 * script writes, so neither the render nor the write can drift from the
 * template.
 */

// Libraries
const path = require('node:path');
const jetpack = require('fs-jetpack');
const { composeWorkflow } = require('@omega.js/devkit/ci-workflows');
const { renderTemplate } = require('@omega.js/devkit/defaults-engine');
const { renderSecretsBlock } = require('@omega.js/config/env-delivery');

// Constants
const ROOT = path.join(__dirname, '..');
const TEMPLATE = path.join(ROOT, 'packages', 'desktop', 'src', 'defaults', '.github', 'workflows', 'build.yml');
const WORKFLOW = path.join(ROOT, '.github', 'workflows', 'playground-desktop.yml');
const TARGET_PATH = 'brands/omega-playground/targets/desktop';
const TARGET_NAME = 'desktop';
const WORKFLOW_NAME = 'Playground desktop release run (test-only)';

// The header replaces the devkit compose header: this file is not a brand's
// scaffold output, nothing reconciles it, and the only thing that rewrites it is
// the script named here.
const HEADER = [
  '# GENERATED by scripts/playground-desktop-workflow.js from the @omega.js/desktop',
  '# workflow template (packages/desktop/src/defaults/.github/workflows/build.yml),',
  `# composed for ${TARGET_PATH}. Do not edit by hand: run`,
  '# `node scripts/playground-desktop-workflow.js` and let it rewrite the file. It',
  '# is never committed to the monorepo: the rehearsal pushes it to the snapshot',
  '# repo, which is the only place it lives.',
  '#',
  '# TEST-ONLY, and never a brand\'s pattern. The playground lives INSIDE this',
  '# monorepo, so its composed workflow sits at a directory GitHub never runs',
  '# workflows from; this copy gives the desktop release run (hosted build, the',
  '# self-hosted EV-token Windows signer, finalize) a repo root to run in, in the',
  '# brand\'s own private rehearsal repo. A real brand is its own repo and gets its',
  '# composed file from any omega verb, with no root install and no script',
  '# (docs/shared/deploys.md).',
  '#',
  '# Dispatched by hand only, and one command does the whole rehearsal: regenerate',
  '# this file, snapshot the working tree onto the rehearsal repo\'s `main`,',
  '# dispatch it there, follow the run (scripts/playground-desktop-rehearsal.js):',
  '#   npm run rehearse:desktop -- --platforms windows --watch',
].join('\n');

// The local era ([docs/shared/brands.md](docs/shared/brands.md)): every
// `@omega.js/*` dep of the playground is a `file:` spec into THIS checkout, so
// the packages have to be installed and their dists built at the repo root
// before a target step can resolve one. Root steps, so they carry no
// `working-directory` and run before the composed target steps of their job.
// `npm install`, never `npm ci`: the rehearsal builds a SNAPSHOT of a working
// tree, whose root lockfile may lag its package.json files until the ship's own
// root `npm install` heals it, and `npm ci` refuses a lagging lockfile outright.
const ROOT_INSTALL = 'npm install && npm run prepare --workspaces --if-present';
const ROOT_INSTALL_COMMENT = [
  '      # The local era: the playground\'s @omega.js deps are `file:` links into THIS',
  '      # checkout, so the monorepo is installed and every package dist is built at',
  '      # the repo root before any step below touches the target.',
];

/**
 * Render the workflow: template → framework render → compose → monorepo edits.
 * @returns {string} the workflow file's contents
 */
function renderWorkflow() {
  const desktop = require(path.join(ROOT, 'packages', 'desktop', 'package.json'));

  // The framework's own scaffold context (packages/desktop/src/commands/lib/ensure-target.js):
  // the Electron-bundled Node major, and the env schema's CI-delivered keys.
  const rendered = renderTemplate(jetpack.read(TEMPLATE), {
    versions: { ...(desktop.engines || {}), node: desktop.omega.nodeRuntime },
    githubSecrets: renderSecretsBlock('desktop', { indent: '  ' }),
  });

  // The header drop below slices from the first `name:` line, so a template that
  // ever opens with something else (a comment block, a `run-name:`) would lose
  // that opening without a word. It is the template's shape, so it is checked
  // here rather than assumed.
  if (!/^name:/.test(rendered)) {
    throw new Error(`${TEMPLATE} no longer starts with a \`name:\` line; the compose-header slice in this script would drop whatever now comes first. Update the slice before regenerating.`);
  }

  const composed = composeWorkflow(rendered, { targetPath: TARGET_PATH, targetName: TARGET_NAME });

  // Drop the compose header (a framework-scaffold mark this file has no business
  // carrying) and name the run for what it is.
  let workflow = composed.slice(composed.search(/^name:/m));
  workflow = workflow.replace(/^name:.*$/m, `name: ${WORKFLOW_NAME}`);

  // `npm ci` reads the lockfile of the nearest workspace ROOT, which for this
  // target is the brand dir, and a brand's lockfile is not committed here, so a
  // fresh checkout has none to read. `npm install` resolves the same tree
  // (the `file:` specs link into the checkout the root install just prepared).
  workflow = workflow.replace(/\bsfw npm ci\b/g, 'sfw npm install');

  return `${HEADER}\n${insertRootInstall(workflow)}`;
}

/**
 * Give every job that checks out the root install, ahead of its first
 * target-scoped step.
 * @param {string} contents - The composed workflow
 * @returns {string} the workflow with the root install steps inserted
 */
function insertRootInstall(contents) {
  const lines = contents.split('\n');

  // Insert back to front so the earlier indices stay valid.
  for (let index = lines.length - 1; index >= 0; index--) {
    if (!/^ {6}- uses: actions\/setup-node@/.test(lines[index])) {
      continue;
    }

    lines.splice(stepEnd(lines, index), 0, '', ...rootInstallStep(matrixJob(lines, index)));
  }

  return lines.join('\n');
}

// Where a step's own lines stop: the next line that is blank (the separator
// belongs to what follows) or belongs to something at or above step level.
function stepEnd(lines, start) {
  let end = start + 1;
  while (end < lines.length && lines[end].search(/\S/) > 6) {
    end++;
  }

  return end;
}

// Does the job holding this step build the OS matrix? Its install runs on
// Windows too, where the runner's default PowerShell breaks npm exactly as the
// template's own comment describes, so that one is gated into a cmd twin.
function matrixJob(lines, index) {
  for (let cursor = index; cursor >= 0; cursor--) {
    if (/^ {2}\S/.test(lines[cursor])) {
      return false;
    }
    if (/^ {4}runs-on:.*matrix\.os/.test(lines[cursor])) {
      return true;
    }
  }

  return false;
}

// The step lines themselves: one plain step, or the cmd/non-cmd pair a matrix
// job needs.
function rootInstallStep(matrix) {
  if (!matrix) {
    return [
      ...ROOT_INSTALL_COMMENT,
      '      - name: Install the monorepo and build every package dist',
      `        run: ${ROOT_INSTALL}`,
    ];
  }

  return [
    ...ROOT_INSTALL_COMMENT,
    '      # `shell: cmd` on Windows for the reason the target steps below give.',
    '      - if: matrix.os == \'windows-latest\'',
    '        shell: cmd',
    `        run: ${ROOT_INSTALL}`,
    '      - if: matrix.os != \'windows-latest\'',
    `        run: ${ROOT_INSTALL}`,
  ];
}

if (require.main === module) {
  const contents = renderWorkflow();
  const changed = jetpack.read(WORKFLOW) !== contents;

  jetpack.write(WORKFLOW, contents);
  console.log(`${changed ? 'Wrote' : 'Unchanged'} .github/workflows/playground-desktop.yml (${TARGET_PATH})`);
}

module.exports = { renderWorkflow, WORKFLOW, TARGET_PATH, WORKFLOW_NAME };
